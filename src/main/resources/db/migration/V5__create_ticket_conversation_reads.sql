CREATE TABLE ticket_conversation_reads (
                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                           ticket_id BIGINT NOT NULL
                                               REFERENCES tickets(id) ON DELETE CASCADE,

                                           user_id BIGINT NOT NULL
                                               REFERENCES users(id) ON DELETE CASCADE,

                                           last_read_message_id BIGINT NOT NULL DEFAULT 0,

                                           CONSTRAINT uq_ticket_conversation_reads
                                               UNIQUE (ticket_id, user_id)
);

CREATE INDEX idx_conversation_reads_user
    ON ticket_conversation_reads(user_id, ticket_id);

-- Initialize existing ticket participants as having read
-- all messages that already exist.
INSERT INTO ticket_conversation_reads
(ticket_id, user_id, last_read_message_id)
SELECT
    participants.ticket_id,
    participants.user_id,
    COALESCE(MAX(messages.id), 0)
FROM (
         SELECT id AS ticket_id, created_by AS user_id
         FROM tickets

         UNION

         SELECT id AS ticket_id, assigned_to AS user_id
         FROM tickets
         WHERE assigned_to IS NOT NULL
     ) AS participants
         LEFT JOIN ticket_messages messages
                   ON messages.ticket_id = participants.ticket_id
GROUP BY participants.ticket_id, participants.user_id
ON CONFLICT (ticket_id, user_id) DO NOTHING;
