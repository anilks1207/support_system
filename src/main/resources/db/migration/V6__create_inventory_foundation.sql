-- 8. Insert stock items, resolving category IDs by category name
INSERT INTO stock_items (
    item_code,
    name,
    category_id,
    unit,
    low_stock_threshold
)
SELECT
    i.item_code,
    i.item_name,
    c.id,
    i.unit,
    i.low_stock_threshold
FROM register_import_items i
         JOIN stock_categories c ON c.name = i.category_name;

-- 9. Initialize each item's balance at Central Store
INSERT INTO stock_balances (
    stock_item_id,
    location_id,
    quantity_on_hand,
    quantity_reserved
)
SELECT
    s.id,
    l.id,
    i.opening_quantity,
    0
FROM register_import_items i
         JOIN stock_items s ON s.item_code = i.item_code
         JOIN locations l ON l.name = 'Central Store';

-- 10. Record positive opening quantities in the audit history.
-- Zero quantities are represented by the initial zero balance.
INSERT INTO stock_transactions (
    stock_item_id,
    location_id,
    transaction_type,
    quantity_change,
    performed_by,
    note
)
SELECT
    s.id,
    l.id,
    'OPENING',
    i.opening_quantity,
    NULL,
    'Initial stock imported by Flyway V6'
FROM register_import_items i
         JOIN stock_items s ON s.item_code = i.item_code
         JOIN locations l ON l.name = 'Central Store'
WHERE i.opening_quantity > 0;

-- 11. Verify the imported register during migration execution
DO $$
    DECLARE
        item_count INTEGER;
        balance_count INTEGER;
    BEGIN
        SELECT COUNT(*) INTO item_count
        FROM stock_items;

        SELECT COUNT(*) INTO balance_count
        FROM stock_balances b
                 JOIN locations l ON l.id = b.location_id
        WHERE l.name = 'Central Store';

        IF item_count <> (SELECT COUNT(*) FROM register_import_items) THEN
            RAISE EXCEPTION
                'V6 import verification failed: expected % stock items, found %',
                (SELECT COUNT(*) FROM register_import_items), item_count;
        END IF;

        IF balance_count <> (SELECT COUNT(*) FROM register_import_items) THEN
            RAISE EXCEPTION
                'V6 balance verification failed: expected % Central Store balances, found %',
                (SELECT COUNT(*) FROM register_import_items), balance_count;
        END IF;
    END $$;
