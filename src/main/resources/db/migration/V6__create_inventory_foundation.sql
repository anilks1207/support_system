-- 3. Stock item master
CREATE TABLE stock_items (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             item_code VARCHAR(50) NOT NULL UNIQUE,
                             name VARCHAR(200) NOT NULL,
                             category_id BIGINT NOT NULL REFERENCES stock_categories(id),
                             unit VARCHAR(30) NOT NULL,
                             low_stock_threshold NUMERIC(14,3) NOT NULL DEFAULT 0,
                             active BOOLEAN NOT NULL DEFAULT TRUE,
                             created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             CONSTRAINT chk_stock_item_threshold
                                 CHECK (low_stock_threshold >= 0)
);

CREATE INDEX idx_stock_items_category ON stock_items(category_id);
CREATE INDEX idx_stock_items_name ON stock_items(name);

-- 4. Stock balances by item and location
CREATE TABLE stock_balances (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                stock_item_id BIGINT NOT NULL REFERENCES stock_items(id),
                                location_id BIGINT NOT NULL REFERENCES locations(id),
                                quantity_on_hand NUMERIC(14,3) NOT NULL DEFAULT 0,
                                quantity_reserved NUMERIC(14,3) NOT NULL DEFAULT 0,
                                updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                CONSTRAINT uq_stock_balance_item_location
                                    UNIQUE (stock_item_id, location_id),
                                CONSTRAINT chk_stock_quantity_nonnegative
                                    CHECK (quantity_on_hand >= 0),
                                CONSTRAINT chk_stock_reserved_nonnegative
                                    CHECK (quantity_reserved >= 0),
                                CONSTRAINT chk_stock_reserved_not_over_on_hand
                                    CHECK (quantity_reserved <= quantity_on_hand)
);

CREATE INDEX idx_stock_balances_location
    ON stock_balances(location_id);

-- 5. Stock movement audit history.
-- performed_by is nullable only for initial imported stock.
CREATE TABLE stock_transactions (
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    stock_item_id BIGINT NOT NULL REFERENCES stock_items(id),
                                    location_id BIGINT NOT NULL REFERENCES locations(id),
                                    transaction_type VARCHAR(30) NOT NULL,
                                    quantity_change NUMERIC(14,3) NOT NULL,
                                    performed_by BIGINT REFERENCES users(id),
                                    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                    note TEXT,
                                    CONSTRAINT chk_stock_transaction_type
                                        CHECK (transaction_type IN (
                                                                    'OPENING', 'PURCHASE', 'ISSUE', 'RETURN',
                                                                    'ADJUSTMENT', 'TRANSFER_IN', 'TRANSFER_OUT'
                                            )),
                                    CONSTRAINT chk_stock_transaction_quantity
                                        CHECK (quantity_change <> 0)
);

CREATE INDEX idx_stock_transactions_item_date
    ON stock_transactions(stock_item_id, created_at);

CREATE INDEX idx_stock_transactions_location_date
    ON stock_transactions(location_id, created_at);

